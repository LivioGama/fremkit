/** Hex SHA-256 of `fingerprint-words.txt` (256 lines, LF, trailing LF). */
export const FINGERPRINT_LIST_SHA256 = '247bec0519f05acf5f8716f8515af0532676cce180409949d265f5670797c930'

/**
 * Four words for a key: the first four bytes of its hash, each looked up in `WORDS`.
 * `keyHash` is the base64url SHA-256 of the key's SPKI, the QR's `k`.
 */
export function fingerprintWords(keyHash: string): string[] {
  const bytes = Buffer.from(keyHash, 'base64url')
  if (bytes.length < 4) throw new Error('a key hash is at least four bytes')
  return [0, 1, 2, 3].map((i) => WORDS[bytes[i]])
}
